#!/usr/bin/env bash
# Copies the canonical eval fixtures into the case directories that use them.
#
# A case.yaml's `scaffold_script` has to name a file inside its own case
# directory — a relative path that escapes it is rejected outright — so a
# fixture shared by several cases cannot be shared by reference. It has to be
# copied, and copying by hand is how copies drift. This script owns them.
#
#   sync-eval-fixtures.sh           write the copies
#   sync-eval-fixtures.sh --check   exit 1 if any copy is stale
set -uo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
EVALS="$ROOT/plugin/evals"
FIXTURES="$EVALS/fixtures"

# Which fixture each case scaffolds with. One line per case: directory, then
# the fixture name (a file in plugin/evals/fixtures/<name>.sh).
MAP='
ready-to-ship          repo
next-version           repo
write-the-changelog    repo
out-the-door           repo
bump-a-dependency      repo
node-version-question  repo
what-changed           repo
open-a-pr              repo
'

CHECK=0
[ "${1:-}" = "--check" ] && CHECK=1

# The copy, with a header that says where it came from so nobody edits it.
render() { # fixture name
  printf '#!/usr/bin/env bash\n'
  printf '# GENERATED by scripts/sync-eval-fixtures.sh from plugin/evals/fixtures/%s.sh\n' "$1"
  printf '# Edit that file and re-run the script; edits here are overwritten.\n'
  tail -n +2 "$FIXTURES/$1.sh"
}

stale=0
written=0
while read -r case_dir fixture; do
  [ -n "${case_dir:-}" ] || continue
  src="$FIXTURES/$fixture.sh"
  dest="$EVALS/$case_dir/scaffold.sh"

  if [ ! -f "$src" ]; then
    printf '  MISSING  fixture %s (needed by %s)\n' "$src" "$case_dir" >&2
    stale=$((stale+1)); continue
  fi
  if [ ! -d "$EVALS/$case_dir" ]; then
    printf '  MISSING  case directory %s\n' "$case_dir" >&2
    stale=$((stale+1)); continue
  fi

  if [ "$CHECK" -eq 1 ]; then
    if [ -f "$dest" ] && render "$fixture" | cmp -s - "$dest"; then
      printf '  ok     %s/scaffold.sh\n' "$case_dir"
    else
      printf '  STALE  %s/scaffold.sh — run scripts/sync-eval-fixtures.sh\n' "$case_dir" >&2
      stale=$((stale+1))
    fi
  else
    render "$fixture" > "$dest"
    chmod +x "$dest"
    printf '  wrote  %s/scaffold.sh (from %s.sh)\n' "$case_dir" "$fixture"
    written=$((written+1))
  fi
done <<< "$MAP"

if [ "$stale" -gt 0 ]; then
  printf '\n%d fixture copy/copies need attention.\n' "$stale" >&2
  exit 1
fi
[ "$CHECK" -eq 1 ] && echo "All fixture copies are current." || printf '\n%d copy/copies written.\n' "$written"
exit 0
